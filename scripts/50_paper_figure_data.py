"""
Write the data behind the manuscript's pgfplots/TikZ figures (paper/data/*) from saved results.
No number in a paper figure is typed by hand: re-run after any result changes (after scripts/44, 47, 49 and 51).

Sources: paper_outputs/tables/{skip_fsm_cert,skip_cstr_cert,mechanism_grounding_auroc,closed_loop_costs_all}.csv
and outputs/sensitivity/*_probe_class/{results,deltas}.csv (scripts/51).

Example:
    python -m scripts.50_paper_figure_data
"""
from __future__ import annotations

import numpy as np
import pandas as pd

from src.utils.manifest import REPO_ROOT

TAB = REPO_ROOT / "paper_outputs" / "tables"
SENS = REPO_ROOT / "outputs" / "sensitivity"
OUT = REPO_ROOT / "paper" / "data"

# model -> row/column index shared by every per-model figure (1 = top row in horizontal charts)
MODELS = {"Qwen2.5-1.5B": 1, "Qwen2.5-3B": 2, "Qwen2.5-3B*": 2, "Qwen2.5-7B (4-bit)": 3, "Llama-3.2-3B": 4,
          "SmolLM2-1.7B": 5}
INTERNALS = "All internals + grounding"


def write(name: str, df: pd.DataFrame) -> None:
    df.to_csv(OUT / f"{name}.dat", sep=" ", index=False, float_format="%.3f")


def skip_frames():
    out = {}
    for dom in ("fsm", "cstr"):
        T = pd.read_csv(TAB / f"skip_{dom}_cert.csv")
        out[dom] = T[(T.tolerance - 0.10).abs() < 1e-9]
    return out


def replacement(skip):
    """RQ1: what the internals-only screen does with each proposal (accept / reject / simulate), per model."""
    for dom, T in skip.items():
        rows = []
        for m, y in MODELS.items():
            s, o = T[(T.model == m) & (T.signal == INTERNALS)], T[(T.model == m) & (T.signal == "Observables")]
            if s.empty:
                continue
            s, o = s.iloc[0], o.iloc[0]
            acc, rej = 100 * s.accepted / s.n, 100 * s.rejected / s.n
            rows.append({"y": y, "acc": acc, "rej": rej, "sim": 100 - acc - rej, "skip": acc + rej,
                         "accfail": int(s.accepted_failures), "accn": int(s.accepted),
                         "certified": int(bool(s.certified)), "rejprec": 100 * (1 - s.rejected_good / max(1, s.rejected)),
                         "obs_skip": o.skipped_pct})
        write(f"replace_{dom}", pd.DataFrame(rows))
        notes = []  # one annotation per bar: what the unchecked decisions cost
        for r in rows:
            acc = (f"{r['accfail']}/{r['accn']} accepts fail" + (" (certified)" if r["certified"] else "")
                   if r["accn"] else "no accepts")
            notes.append(f"\\rnote{{{r['y']}}}{{\\textbf{{{r['skip']:.0f}\\,\\%}} skipped: {acc}; "
                         f"{r['rejprec']:.0f}\\,\\% of rejects fail}}")
        (OUT / f"replace_notes_{dom}.tex").write_text(
            "% generated by scripts/50_paper_figure_data.py; do not edit\n" + "\n".join(notes) + "\n", encoding="utf-8")


def sensitivity_frames():
    """Latest probe-class sensitivity run per domain (scripts/51)."""
    R, D = [], []
    for run in sorted(SENS.glob("*_probe_class")):
        r, d = pd.read_csv(run / "results.csv"), pd.read_csv(run / "deltas.csv")
        for dom in r.domain.unique():
            R = [x for x in R if x.domain.iloc[0] != dom] + [r[r.domain == dom]]
            D = [x for x in D if x.domain.iloc[0] != dom] + [d[d.domain == dom]]
    return pd.concat(R), pd.concat(D)


def heatmap(D):
    """RQ2: change in calls skipped when internals (+ grounding) are added, against baselines of increasing
    strength or fairness. Written as TikZ macro calls: \\hcell{col}{row}{fill}{value}{ci}."""
    D = D[(D.tolerance - 0.10).abs() < 1e-9]
    rows = {"fsm": [("C1", "combined [logistic]"), ("C1", "combined [gbm]"),
                    ("C4", "validator-free combined [logistic]"), ("C4", "validator-free combined [gbm]")],
            "cstr": [("C1", "combined [logistic]"), ("C1", "combined [gbm]")]}
    for dom, spec in rows.items():
        lines = []
        for j, (comp, a) in enumerate(spec, start=1):
            for m, x in MODELS.items():
                r = D[(D.domain == dom) & (D.model == m) & (D.comparison == comp) & (D.a == a)]
                if r.empty:
                    continue
                r = r.iloc[0]
                sig = r.ci_lo > 0 or r.ci_hi < 0
                tone = min(75, 12 + 3.5 * abs(r.delta_pts))
                fill = ("cGrd" if r.delta_pts > 0 else "cInt") + f"!{tone:.0f}" if sig else "black!4"
                lines.append(f"\\hcell{{{x}}}{{{j}}}{{{fill}}}{{${r.delta_pts:+.1f}$}}"
                             f"{{$[{r.ci_lo:+.1f},\\,{r.ci_hi:+.1f}]$}}{{{int(sig)}}}")
        (OUT / f"heat_{dom}.tex").write_text("% generated by scripts/50_paper_figure_data.py; do not edit\n"
                                             + "\n".join(lines) + "\n", encoding="utf-8")


def mechanism():
    M = pd.read_csv(TAB / "mechanism_grounding_auroc.csv")
    rows = []
    for m, y in MODELS.items():
        f = M[(M.domain == "FSM") & (M.model == m)]
        c = M[(M.domain == "CSTR") & M.model.isin([m, m + "*"])]
        if len(f) and len(c):
            rows.append({"y": y, "fsm": f.auroc_low_grounding_predicts_failure.iloc[0],
                         "cstr": c.auroc_low_grounding_predicts_failure.iloc[0]})
    write("mechanism", pd.DataFrame(rows))


POLICIES = [  # (row, key, logged policy name, first-proposal-only variant or None); row 5 = top
    (5, "nv", "Never validate", None), (4, "rand", "Random routing", None),
    (3, "obs", "Observables probe", "Observables probe, first-proposal-only"),
    (2, "comb", "Obs. + internals + grounding probe", "Obs. + internals + grounding, first-proposal-only"),
    (1, "int", "Internals-only probe", "Internals-only, first-proposal-only"),
]


def closed_loop():
    """RQ4: dot plot (unsafe executions, calls avoided, recovery change) and saving-vs-validator-cost curves."""
    C = pd.read_csv(TAB / "closed_loop_costs_all.csv")
    av = C[C.policy == "Always validate"].set_index("model")
    dots = {k: [] for _, k, _, _ in POLICIES}
    ghosts = []
    for m in C.model.unique():
        x = MODELS[m]
        for row, key, name, r0 in POLICIES:
            main = C[(C.model == m) & (C.policy == name)].iloc[0]
            dep = C[(C.model == m) & (C.policy == r0)] if r0 else pd.DataFrame()
            d = dep.iloc[0] if len(dep) else main
            y = row + 0.13 * (x - 3)
            dots[key].append({"y": y, "m": f"m{x}", "unsafe": max(d.unsafe_executions, 0.5),
                              "unsafe_n": int(d.unsafe_executions), "calls": d.calls_avoided_pct,
                              "drec": d.recovered_pct - av.loc[m, "recovered_pct"]})
            if len(dep) and dep.iloc[0].unsafe_executions != main.unsafe_executions:
                ghosts.append({"y": y, "m": f"m{x}", "u0": max(main.unsafe_executions, 0.5),
                               "u1": max(d.unsafe_executions, 0.5), "c0": main.calls_avoided_pct,
                               "c1": d.calls_avoided_pct, "r0": main.recovered_pct - av.loc[m, "recovered_pct"],
                               "r1": d.recovered_pct - av.loc[m, "recovered_pct"]})
    for k, rows in dots.items():
        write(f"cl_{k}", pd.DataFrame(rows))
    write("cl_ghost", pd.DataFrame(ghosts))
    # relative saving s(c) = 1 - C_p(c) / C_AV(c), C(c) = G + N c, for the deployed (R0 where run) screens
    grid = np.arange(0, 121, 2)
    for _, key, name, r0 in POLICIES[2:]:
        cols = {"c": grid}
        for m in C.model.unique():
            dep = C[(C.model == m) & (C.policy == r0)]
            d = dep.iloc[0] if len(dep) else C[(C.model == m) & (C.policy == name)].iloc[0]
            a = av.loc[m]
            G = lambda r: r.gen_s + r.internals_s + r.grounding_s  # noqa: E731
            cols[f"m{MODELS[m]}"] = 100 * (1 - (G(d) + d.validator_calls_per_ep * grid)
                                           / (G(a) + a.validator_calls_per_ep * grid))
        write(f"save_{key}", pd.DataFrame(cols))
    meas = C[C.policy == "Always validate"].measured_validator_s_per_call
    write("save_measured", pd.DataFrame({"lo": [meas.min()], "hi": [meas.max()]}))


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for f in OUT.glob("*.dat"):
        f.unlink()  # data files of earlier figure designs must not linger
    skip = skip_frames()
    replacement(skip)
    heatmap(sensitivity_frames()[1])
    mechanism()
    closed_loop()
    print("figure data:", sorted(p.name for p in OUT.iterdir()))


if __name__ == "__main__":
    main()
